#!/usr/bin/env node
// catalog.js — regenerate docs/CATALOG.md from the agents, roster, skills and commands on disk.
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
function fm(file) {
  const s = fs.readFileSync(file, 'utf8');
  const end = s.indexOf('\n---', 3);
  const out = {};
  if (s.startsWith('---') && end !== -1) for (const line of s.slice(4, end).split('\n')) { const m = line.match(/^([A-Za-z_-]+):\s*(.*)$/); if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, ''); }
  const o = s.match(/origin: ([^\n>]+)/); out.origin = (out.origin || (o ? o[1] : '')).trim();
  return out;
}
const short = (d, n = 140) => (d || '').replace(/\|/g, '\\|').slice(0, n) + ((d || '').length > n ? '…' : '');
const originTag = (o) => o.replace(/\s*\(.*$/, '').replace('affaan-m/ECC', 'ECC').replace('msitarzewski/agency-agents', 'agency').replace('mattpocock/skills', 'mattpocock').replace('addyosmani/agent-skills', 'addyosmani').replace('github/spec-kit', 'spec-kit');
let md = '# Forge catalog\n\n_Generated by `node scripts/catalog.js`. Do not edit by hand._\n\n';

md += '## Commands (`/forge:<name>`)\n\n| Command | Description |\n|---|---|\n';
for (const f of fs.readdirSync(path.join(ROOT, 'commands')).filter((f) => f.endsWith('.md')).sort()) md += `| \`/forge:${f.slice(0, -3)}\` | ${short(fm(path.join(ROOT, 'commands', f)).description, 200)} |\n`;

md += '\n## Core agents (`agents/`, loaded by the plugin)\n\n| Agent | Model | Origin | Description |\n|---|---|---|---|\n';
for (const f of fs.readdirSync(path.join(ROOT, 'agents')).filter((f) => f.endsWith('.md')).sort()) { const m = fm(path.join(ROOT, 'agents', f)); md += `| \`${m.name}\` | ${m.model || 'inherit'} | ${originTag(m.origin)} | ${short(m.description)} |\n`; }

md += '\n## Roster (`roster/<division>/`, install with `node scripts/install.js --division <name>`)\n';
for (const d of fs.readdirSync(path.join(ROOT, 'roster')).sort()) {
  md += `\n### ${d}\n\n| Agent | Origin | Description |\n|---|---|---|\n`;
  for (const f of fs.readdirSync(path.join(ROOT, 'roster', d)).filter((f) => f.endsWith('.md')).sort()) { const m = fm(path.join(ROOT, 'roster', d, f)); md += `| \`${m.name}\` | ${originTag(m.origin)} | ${short(m.description)} |\n`; }
}

md += '\n## Skills (`skills/<category>/<name>/SKILL.md`)\n';
for (const cat of fs.readdirSync(path.join(ROOT, 'skills')).sort()) {
  md += `\n### ${cat}\n\n| Skill | Invocation | Origin | Description |\n|---|---|---|---|\n`;
  for (const sk of fs.readdirSync(path.join(ROOT, 'skills', cat)).sort()) {
    const m = fm(path.join(ROOT, 'skills', cat, sk, 'SKILL.md'));
    const inv = m['disable-model-invocation'] === 'true' ? 'user (`/forge:' + sk + '`)' : 'auto + user';
    md += `| \`${sk}\` | ${inv} | ${originTag(m.origin)} | ${short(m.description)} |\n`;
  }
}
md += '\n## Rules (`rules/`)\n\n' + fs.readdirSync(path.join(ROOT, 'rules')).filter((d) => fs.statSync(path.join(ROOT, 'rules', d)).isDirectory()).sort().map((d) => `- \`${d}\`: ` + fs.readdirSync(path.join(ROOT, 'rules', d)).map((f) => f.replace('.md', '')).join(', ')).join('\n') + '\n';
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'CATALOG.md'), md);
console.log('docs/CATALOG.md written');
